#!/usr/bin/env bash
# Installs the signed release APK and (via bundletool) the signed AAB on an emulator in airplane mode,
# launches each, and checks the app starts without crashing. Airplane mode stays ON throughout so no
# real AdMob ad is ever requested from a test device.
set -uo pipefail
DIR="$1"; OUT="$2"; PKG=com.robertlangat.bibledaily
mkdir -p "$OUT"; status=0
APK=$(ls "$DIR"/*.apk); AAB=$(ls "$DIR"/*.aab)
adb wait-for-device
adb shell settings put global hide_error_dialogs 1 || true
adb shell cmd connectivity airplane-mode enable; sleep 5
echo "Android $(adb shell getprop ro.build.version.release | tr -d '\r') (API $(adb shell getprop ro.build.version.sdk | tr -d '\r'))" | tee "$OUT/summary.txt"
echo "airplane_mode_on=$(adb shell settings get global airplane_mode_on | tr -d '\r')" | tee -a "$OUT/summary.txt"

launch_check () {
  local name="$1"
  adb logcat -c
  adb shell am start -W -n $PKG/.MainActivity | tee -a "$OUT/summary.txt"
  sleep 15
  adb exec-out screencap -p > "$OUT/$name.png"
  if adb shell pidof $PKG >/dev/null && ! adb logcat -d | grep -q "FATAL EXCEPTION"; then
    echo "$name: PASSED (app running, no crash)" | tee -a "$OUT/summary.txt"
  else
    echo "$name: FAILED" | tee -a "$OUT/summary.txt"; status=1
    adb logcat -d | grep -A30 "FATAL EXCEPTION" | tee -a "$OUT/summary.txt"
  fi
  adb logcat -d -s BibleDaily:* BibleDailyAds:* > "$OUT/$name-logcat.txt" || true
  adb shell am force-stop $PKG
}

echo "== Signed universal APK" | tee -a "$OUT/summary.txt"
adb uninstall $PKG >/dev/null 2>&1 || true
adb install "$APK" | tee -a "$OUT/summary.txt"
adb shell dumpsys package $PKG | grep -E "versionName|versionCode|targetSdk" | head -3 | tee -a "$OUT/summary.txt"
launch_check signed-apk

echo "== Signed AAB (APKs generated by bundletool for this device, as stores do)" | tee -a "$OUT/summary.txt"
adb uninstall $PKG >/dev/null 2>&1 || true
java -jar bundletool.jar build-apks --bundle="$AAB" --output=app.apks --connected-device \
  --ks=app/debug.keystore --ks-pass=pass:android --ks-key-alias=androiddebugkey --key-pass=pass:android
java -jar bundletool.jar install-apks --apks=app.apks | tee -a "$OUT/summary.txt"
launch_check aab-install

echo "airplane_mode_on at end=$(adb shell settings get global airplane_mode_on | tr -d '\r')" | tee -a "$OUT/summary.txt"
exit $status
